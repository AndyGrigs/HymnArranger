"""Стильові обробки — форма цілком, а не окрема варіація.

На відміну від `meters/`, де пресет описує ОДНУ фактуру, стиль задає
всю п'єсу: послідовність строф, зв'язки між ними, регістровий план і коду.
Старі режими лишаються недоторканими — стиль додається поруч, а не замість.
"""

from . import sakala

STYLES = {
    'sakala': sakala,
}


def get(name: str):
    if name not in STYLES:
        raise KeyError(f'Невідомий стиль {name!r}. Доступні: {", ".join(STYLES)}')
    return STYLES[name]
